"""Known-answer tests for the non-deep-learning baselines.

Both baselines are exercised on synthetic data generated by the same
Michelson forward model the estimators assume, so the correct answer is known
exactly and a failure means the estimator is wrong -- not that the hardware
is noisy.
"""

import numpy as np
import pytest
import torch

from smi.analysis.baseline_fit import (
    PD_WAVELENGTHS_UM,
    fit_phase_amplitude,
    forward_model_residual,
    inverse_fit,
    windowed_forward_model_residual,
)
from smi.synthetic.coil_driver import MS_PER_S
from smi.synthetic.interferometers import MichelsonInterferometer

SAMPLE_RATE = 488281.25

# The Viterbi decode is a long sequential loop over time samples. On a GPU it
# is a few hundred milliseconds; on CPU it is tens of seconds. Use the GPU
# when the machine has one so these known-answer checks stay cheap enough to
# live in the unit suite, and shrink the problem on CPU-only machines (CI).
DEVICE = 'cuda:0' if torch.cuda.is_available() else 'cpu'
DECODE_SAMPLES = 2048 if torch.cuda.is_available() else 768
GRID_POINTS = 1601 if torch.cuda.is_available() else 801
ENSEMBLE_SHOTS = 12 if torch.cuda.is_available() else 4


def _band_limited_displacement(
    n_samples: int, seed: int, amplitude_um: float = 0.35
) -> np.ndarray:
    """Smooth multi-tone displacement in the band the speaker actually drives.

    Returns:
        Zero-mean displacement in microns, shape ``(n_samples,)``.
    """
    rng = np.random.default_rng(seed)
    t = np.arange(n_samples) / SAMPLE_RATE
    disp = np.zeros(n_samples)
    for freq, weight in ((120.0, 1.0), (310.0, 0.6), (700.0, 0.3)):
        disp += weight * np.sin(2 * np.pi * freq * t + rng.uniform(0, 2 * np.pi))
    disp -= disp.mean()
    return disp * (amplitude_um / disp.std())


def _best_sign_rmse(estimate: np.ndarray, truth: np.ndarray) -> float:
    """RMSE under the better of the two sign conventions.

    ``cos`` is even, so the interferometer signals are identical for ``d(t)``
    and ``-d(t)``: the overall sign is genuinely unobservable from the
    fringes and must not be scored as an error.
    """
    return min(
        float(np.sqrt(np.mean((estimate - truth) ** 2))),
        float(np.sqrt(np.mean((-estimate - truth) ** 2))),
    )


def _synthesize(displacement: np.ndarray, phases, amplitudes) -> np.ndarray:
    """Build three-channel PD signals with the project's Michelson model."""
    channels = []
    for wavelength, phase, amp in zip(
        PD_WAVELENGTHS_UM.values(), phases, amplitudes, strict=True
    ):
        interferometer = MichelsonInterferometer(wavelength=wavelength, phase=phase)
        signal = amp * interferometer.get_interferometer_output(displacement)
        channels.append(signal - signal.mean())
    return np.stack(channels)


class TestClosedFormPhaseAmplitudeFit:
    """The method-1 fit must recover analytically known phase and amplitude."""

    @pytest.mark.parametrize('true_phase', [-2.5, -0.7, 0.0, 0.4, 1.9, 3.0])
    def test_recovers_known_phase_and_amplitude(self, true_phase: float) -> None:
        theta = np.linspace(0, 40 * np.pi, 4096)
        true_amplitude = 0.37
        signal = true_amplitude * np.cos(theta + true_phase)

        fit = fit_phase_amplitude(signal, theta)

        assert fit.amplitude == pytest.approx(true_amplitude, rel=1e-9)
        # Compare on the circle so the (-pi, pi] wrap is not a false failure.
        wrapped = np.angle(np.exp(1j * (fit.phase - true_phase)))
        assert wrapped == pytest.approx(0.0, abs=1e-9)
        assert fit.rmse == pytest.approx(0.0, abs=1e-9)
        assert fit.r_squared == pytest.approx(1.0, abs=1e-9)

    def test_recovers_constant_offset(self) -> None:
        theta = np.linspace(0, 30 * np.pi, 2048)
        signal = 0.2 * np.cos(theta - 1.1) + 0.05

        fit = fit_phase_amplitude(signal, theta)

        assert fit.offset == pytest.approx(0.05, abs=1e-9)
        assert fit.amplitude == pytest.approx(0.2, rel=1e-9)

    def test_noise_shows_up_as_residual_rmse(self) -> None:
        rng = np.random.default_rng(7)
        theta = np.linspace(0, 60 * np.pi, 8192)
        noise_sigma = 0.02
        signal = 0.3 * np.cos(theta + 0.8) + rng.normal(0, noise_sigma, theta.size)

        fit = fit_phase_amplitude(signal, theta)

        # With three free parameters out of 8192 samples, the residual RMSE is
        # the injected noise level to within sampling error.
        assert fit.rmse == pytest.approx(noise_sigma, rel=0.05)
        assert fit.amplitude == pytest.approx(0.3, rel=0.02)

    def test_rejects_mismatched_shapes(self) -> None:
        with pytest.raises(ValueError, match='matching shape'):
            fit_phase_amplitude(np.zeros(10), np.zeros(11))


class TestForwardModelResidual:
    """Method 1 against a signal the Michelson model generates exactly."""

    def test_exact_model_gives_zero_residual(self) -> None:
        disp = _band_limited_displacement(4096, seed=3)
        wavelength = 0.635
        interferometer = MichelsonInterferometer(wavelength=wavelength, phase=1.234)
        signal = 0.11 * interferometer.get_interferometer_output(disp)

        fit = forward_model_residual(signal, disp, wavelength)

        assert fit.r_squared == pytest.approx(1.0, abs=1e-10)
        assert fit.rmse < 1e-12
        assert fit.amplitude == pytest.approx(0.11, rel=1e-8)
        wrapped = np.angle(np.exp(1j * (fit.phase - 1.234)))
        assert wrapped == pytest.approx(0.0, abs=1e-8)

    def test_wrong_displacement_gives_large_residual(self) -> None:
        """A mis-scaled displacement must not fit -- otherwise the metric is
        blind to exactly the calibration error it exists to detect.
        """
        disp = _band_limited_displacement(4096, seed=5)
        wavelength = 0.635
        interferometer = MichelsonInterferometer(wavelength=wavelength, phase=0.0)
        signal = interferometer.get_interferometer_output(disp)

        good = forward_model_residual(signal, disp, wavelength)
        bad = forward_model_residual(signal, disp * 1.3, wavelength)

        assert good.r_squared > 0.999
        assert bad.r_squared < 0.5


def _drifting_fringes(
    displacement: np.ndarray, wavelength_um: float, drift_radians: float
) -> np.ndarray:
    """Michelson fringes with a slow phase ramp added across the record.

    The ramp stands in for the within-shot phase drift measured in the real
    acquisitions (1-2.7 fringes of speckle and path drift). It is the term a
    single global ``(cos, sin, 1)`` fit cannot absorb and a windowed refit can.

    Args:
        displacement: Mirror displacement (microns), shape ``(n,)``.
        wavelength_um: Laser wavelength (microns).
        drift_radians: Total phase ramp accumulated over the record.

    Returns:
        Zero-mean fringe signal, shape ``(n,)``.
    """
    ramp = np.linspace(0.0, drift_radians, displacement.size)
    signal = np.cos(4.0 * np.pi / wavelength_um * displacement + ramp)
    return signal - signal.mean()


class TestWindowedForwardModelResidual:
    """The windowed refit must measure agreement, not absorb everything."""

    WAVELENGTH = 0.635
    DRIFT_RADIANS = 2.0 * np.pi * 2.0
    AMPLITUDE_UM = 3.0
    N_SAMPLES = 16384

    def _signal(self, seed: int, drift: float) -> tuple[np.ndarray, np.ndarray]:
        """Drifting fringes and the displacement that generated them."""
        disp = _band_limited_displacement(
            self.N_SAMPLES, seed=seed, amplitude_um=self.AMPLITUDE_UM
        )
        return _drifting_fringes(disp, self.WAVELENGTH, drift), disp

    def test_windowing_recovers_variance_lost_to_phase_drift(self) -> None:
        signal, disp = self._signal(seed=11, drift=self.DRIFT_RADIANS)

        global_fit = forward_model_residual(signal, disp, self.WAVELENGTH)
        windowed = windowed_forward_model_residual(
            signal, disp, self.WAVELENGTH, window_samples=1024
        )

        assert global_fit.r_squared < 0.6
        assert windowed.r_squared > global_fit.r_squared + 0.25

    def test_without_drift_both_fits_are_high(self) -> None:
        """Windowing must not be a blanket R^2 inflator.

        Without this companion assertion the drift test above would pass even
        if short windows simply fit anything handed to them.
        """
        signal, disp = self._signal(seed=11, drift=0.0)

        global_fit = forward_model_residual(signal, disp, self.WAVELENGTH)
        windowed = windowed_forward_model_residual(
            signal, disp, self.WAVELENGTH, window_samples=1024
        )

        assert global_fit.r_squared > 0.99
        assert windowed.r_squared > 0.99

    def test_scrambled_theta_control_stays_low(self) -> None:
        """A windowed R^2 is only evidence beside its control.

        The control has the identical window count and parameter count but
        takes ``theta`` from a different shot, so whatever it scores is the
        overfitting capacity of the windowing alone.
        """
        signal, disp = self._signal(seed=11, drift=self.DRIFT_RADIANS)
        other = _band_limited_displacement(
            self.N_SAMPLES, seed=12, amplitude_um=self.AMPLITUDE_UM
        )

        real = windowed_forward_model_residual(
            signal, disp, self.WAVELENGTH, window_samples=1024
        )
        control = windowed_forward_model_residual(
            signal, other, self.WAVELENGTH, window_samples=1024
        )

        assert control.r_squared < real.r_squared - 0.25
        assert control.r_squared < 0.35

    def test_full_length_window_equals_global_fit(self) -> None:
        """Pooling must be exact, or the two columns are not comparable."""
        signal, disp = self._signal(seed=7, drift=self.DRIFT_RADIANS)

        global_fit = forward_model_residual(signal, disp, self.WAVELENGTH)
        windowed = windowed_forward_model_residual(
            signal, disp, self.WAVELENGTH, window_samples=self.N_SAMPLES
        )

        assert windowed.r_squared == pytest.approx(global_fit.r_squared, abs=1e-12)
        assert windowed.rmse == pytest.approx(global_fit.rmse, rel=1e-12)

    def test_window_none_is_the_global_fit(self) -> None:
        signal, disp = self._signal(seed=7, drift=self.DRIFT_RADIANS)

        global_fit = forward_model_residual(signal, disp, self.WAVELENGTH)
        windowed = windowed_forward_model_residual(
            signal, disp, self.WAVELENGTH, window_samples=None
        )

        assert windowed.r_squared == pytest.approx(global_fit.r_squared, abs=1e-12)
        assert windowed.n_windows == 1

    def test_record_length_not_a_multiple_of_the_window(self) -> None:
        """A ragged tail must be scored, not silently dropped."""
        n = 1024 * 3 + 500
        disp = _band_limited_displacement(n, seed=13, amplitude_um=self.AMPLITUDE_UM)
        signal = _drifting_fringes(disp, self.WAVELENGTH, self.DRIFT_RADIANS)

        windowed = windowed_forward_model_residual(
            signal, disp, self.WAVELENGTH, window_samples=1024
        )

        assert windowed.n_windows == 4
        assert 0.0 < windowed.r_squared <= 1.0

    def test_pooling_is_variance_weighted_not_an_average_of_ratios(self) -> None:
        """Quiet windows must not vote as loudly as windows full of fringes.

        One window carries all the motion and the model explains it; the rest
        are near-silent noise the model cannot explain, so their per-window
        R^2 is ~0. Averaging the per-window ratios would report ~1/8 and call
        a near-perfect fit a failure. Pooling the sums of squares weights each
        window by the variance it actually contains, which is also what keeps
        the number comparable to the global fit.
        """
        window = 256
        n = window * 8
        wavelength = 0.635
        rng = np.random.default_rng(0)

        t = np.arange(n) / SAMPLE_RATE
        disp = np.zeros(n)
        disp[:window] = 2.0 * np.sin(2 * np.pi * 400.0 * t[:window])
        signal = np.cos(4 * np.pi / wavelength * disp)
        noise = rng.standard_normal(n) * 0.01
        noise[:window] = 0.0

        windowed = windowed_forward_model_residual(
            signal + noise, disp, wavelength, window_samples=window
        )

        # Averaging per-window R^2 would land near 1 / 8 = 0.125.
        assert windowed.r_squared > 0.9

    def test_pooled_total_variance_uses_the_whole_record_mean(self) -> None:
        """The denominator must be the variance the global fit measures.

        Each window here sits at its own DC level. Taking the total sum of
        squares about each window's own mean would delete that between-window
        spread from the denominator, inflating R^2 for variance the fit merely
        re-baselined away rather than explained.
        """
        window = 1024
        n = window * 8
        wavelength = 0.635
        rng = np.random.default_rng(1)

        t = np.arange(n) / SAMPLE_RATE
        disp = 0.9 * np.sin(2 * np.pi * 300.0 * t)
        fringes = np.cos(4 * np.pi / wavelength * disp)
        signal = fringes + 0.7 * rng.standard_normal(n)
        signal = signal + np.repeat(rng.standard_normal(8) * 4.0, window)

        windowed = windowed_forward_model_residual(
            signal, disp, wavelength, window_samples=window
        )

        # Per-window-mean pooling would report ~0.47 on this signal.
        assert windowed.r_squared > 0.9

    def test_rejects_non_positive_window(self) -> None:
        """A zero or negative window is a caller mistake, not a global fit.

        The CLI spells "global only" as ``None``; silently treating 0 the same
        way would hide a mis-parsed argument.
        """
        signal, disp = self._signal(seed=7, drift=self.DRIFT_RADIANS)

        with pytest.raises(ValueError, match='must be positive'):
            windowed_forward_model_residual(
                signal, disp, self.WAVELENGTH, window_samples=0
            )

    def test_rejects_mismatched_shapes(self) -> None:
        with pytest.raises(ValueError, match='matching shape'):
            windowed_forward_model_residual(np.zeros(10), np.zeros(11), 0.635)

    def test_window_longer_than_record_falls_back_to_one_window(self) -> None:
        signal, disp = self._signal(seed=7, drift=self.DRIFT_RADIANS)

        global_fit = forward_model_residual(signal, disp, self.WAVELENGTH)
        windowed = windowed_forward_model_residual(
            signal, disp, self.WAVELENGTH, window_samples=self.N_SAMPLES * 4
        )

        assert windowed.n_windows == 1
        assert windowed.r_squared == pytest.approx(global_fit.r_squared, abs=1e-12)


class TestInverseFit:
    """Method 2 must recover a known displacement from PD signals alone."""

    def test_recovers_known_displacement(self) -> None:
        """A clean single shot with generic phases must decode almost exactly.

        Tolerance is set against the physics, not against the observed
        output: 0.02 um is under a tenth of the shortest half-wavelength
        fringe (0.515/2 = 0.2575 um), so passing means the decoder resolved
        the correct fringe order rather than landing on a neighbour.
        """
        disp = _band_limited_displacement(DECODE_SAMPLES, seed=11, amplitude_um=0.30)
        signals = _synthesize(disp, phases=(0.3, -1.1, 2.2), amplitudes=(1.0, 0.8, 1.2))

        result = inverse_fit(
            signals,
            sample_rate=SAMPLE_RATE,
            wavelengths_um=list(PD_WAVELENGTHS_UM.values()),
            displacement_limit_um=1.5,
            grid_points=GRID_POINTS,
            max_speed_um_per_ms=4.0,
            device=DEVICE,
        )

        assert _best_sign_rmse(result.displacement[0], disp) < 0.02

    def test_recovers_displacement_across_random_phases(self) -> None:
        """The decoder must work for arbitrary interferometer phase offsets.

        Real interferometers sit at an uncontrolled phase, so a single
        hand-picked phase triple would not show whether the estimator is
        generally reliable. Scored over an ensemble: the typical shot must
        decode tightly and the large majority must decode at all.
        """
        n_shots = ENSEMBLE_SHOTS
        rng = np.random.default_rng(99)
        shots = [
            _band_limited_displacement(DECODE_SAMPLES, seed=200 + i, amplitude_um=0.30)
            for i in range(n_shots)
        ]
        batch = np.stack(
            [
                _synthesize(d, rng.uniform(0, 2 * np.pi, 3), (1.0, 1.0, 1.0))
                for d in shots
            ]
        )

        result = inverse_fit(
            batch,
            sample_rate=SAMPLE_RATE,
            wavelengths_um=list(PD_WAVELENGTHS_UM.values()),
            displacement_limit_um=1.5,
            grid_points=GRID_POINTS,
            max_speed_um_per_ms=4.0,
            device=DEVICE,
        )

        nrmse = np.array(
            [
                _best_sign_rmse(result.displacement[i], shots[i]) / shots[i].std()
                for i in range(n_shots)
            ]
        )
        assert np.median(nrmse) < 0.06
        assert (nrmse < 0.10).mean() >= 0.75

    def test_recovers_velocity(self) -> None:
        """Velocity must follow from the decode, not just displacement.

        The decoded displacement is grid-quantized, so this is really a check
        that the derivative is taken in a way that does not amplify the
        quantization step into nonsense.
        """
        disp = _band_limited_displacement(DECODE_SAMPLES, seed=17, amplitude_um=0.30)
        # um/ms, matching inverse_fit's output unit: displacement is um and
        # the time step is in milliseconds.
        true_velocity = np.gradient(disp, MS_PER_S / SAMPLE_RATE)
        signals = _synthesize(disp, phases=(1.0, 2.0, 3.0), amplitudes=(1.0, 1.0, 1.0))

        result = inverse_fit(
            signals,
            sample_rate=SAMPLE_RATE,
            wavelengths_um=list(PD_WAVELENGTHS_UM.values()),
            displacement_limit_um=1.5,
            grid_points=GRID_POINTS,
            max_speed_um_per_ms=4.0,
            device=DEVICE,
        )

        nrmse = _best_sign_rmse(result.velocity[0], true_velocity) / true_velocity.std()
        assert nrmse < 0.30

    def test_velocity_is_um_per_ms(self) -> None:
        """The decoded velocity is um/ms, not um/s.

        The other velocity tests normalize by the true velocity's own standard
        deviation, so they are blind to an overall scale error. This one is
        not: it compares absolute magnitudes against a reference built with an
        explicit millisecond time step.
        """
        disp = _band_limited_displacement(DECODE_SAMPLES, seed=17, amplitude_um=0.30)
        signals = _synthesize(disp, phases=(1.0, 2.0, 3.0), amplitudes=(1.0, 1.0, 1.0))

        result = inverse_fit(
            signals,
            sample_rate=SAMPLE_RATE,
            wavelengths_um=list(PD_WAVELENGTHS_UM.values()),
            displacement_limit_um=1.5,
            grid_points=GRID_POINTS,
            max_speed_um_per_ms=4.0,
            device=DEVICE,
        )

        expected_rms = float(np.std(np.gradient(disp, MS_PER_S / SAMPLE_RATE)))
        actual_rms = float(np.std(result.velocity[0]))
        # A um/s result would be 1000x this; 25% allows for decode error.
        assert 0.75 * expected_rms < actual_rms < 1.25 * expected_rms

    def test_velocity_derivative_beats_naive_difference(self) -> None:
        """The smoothed derivative must actually help, not just exist."""
        disp = _band_limited_displacement(DECODE_SAMPLES, seed=17, amplitude_um=0.30)
        # um/ms, matching inverse_fit's output unit: displacement is um and
        # the time step is in milliseconds.
        true_velocity = np.gradient(disp, MS_PER_S / SAMPLE_RATE)
        signals = _synthesize(disp, phases=(1.0, 2.0, 3.0), amplitudes=(1.0, 1.0, 1.0))

        result = inverse_fit(
            signals,
            sample_rate=SAMPLE_RATE,
            wavelengths_um=list(PD_WAVELENGTHS_UM.values()),
            displacement_limit_um=1.5,
            grid_points=GRID_POINTS,
            max_speed_um_per_ms=4.0,
            device=DEVICE,
        )
        naive = np.gradient(result.displacement[0], MS_PER_S / SAMPLE_RATE)

        smoothed_err = _best_sign_rmse(result.velocity[0], true_velocity)
        naive_err = _best_sign_rmse(naive, true_velocity)
        assert smoothed_err < 0.5 * naive_err

    def test_batched_shots_match_single_shot(self) -> None:
        """Batching is an efficiency detail; it must not change the answer."""
        shots = [
            _band_limited_displacement(1024, seed=s, amplitude_um=0.25)
            for s in (21, 22)
        ]
        batch = np.stack(
            [_synthesize(d, (0.4, -0.6, 1.7), (1.0, 0.9, 1.1)) for d in shots]
        )

        kwargs = {
            'sample_rate': SAMPLE_RATE,
            'wavelengths_um': list(PD_WAVELENGTHS_UM.values()),
            'displacement_limit_um': 1.2,
            'grid_points': 601,
            'max_speed_um_per_ms': 4.0,
            'phase_grid_points': 8,
            'phase_search_samples': 384,
            'device': DEVICE,
        }
        batched = inverse_fit(batch, **kwargs)
        for j in range(2):
            single = inverse_fit(batch[j], **kwargs)
            np.testing.assert_allclose(
                single.displacement[0], batched.displacement[j], atol=1e-9
            )

    def test_rejects_channel_count_mismatch(self) -> None:
        with pytest.raises(ValueError, match='wavelengths'):
            inverse_fit(
                np.zeros((3, 256)),
                sample_rate=SAMPLE_RATE,
                wavelengths_um=[0.635, 0.675],
                displacement_limit_um=1.0,
                grid_points=101,
            )
