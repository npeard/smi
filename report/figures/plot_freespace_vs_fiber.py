#!/usr/bin/env python
"""The distribution shift between the free-space and multimode-fiber datasets.

The two acquisitions drive the same speaker with the same waveform family, but
the two files were generated by separate, unseeded random draws: a shared shot
index does not mean a shared drive waveform, and a single-shot overlay would
be comparing two unrelated realizations as though they were matched. (Shot 7,
for instance: correlation +0.116 between the two files' drive waveforms, RMS
0.0269 V free space against 0.1475 V fiber -- essentially uncorrelated and a
5.5x amplitude mismatch.)

The mean amplitude spectrum sidesteps that problem: it is a distribution-level
statistic over many shots of each acquisition, not a claim about any one
shot's waveform matching the other file's. Any difference it shows is the
fiber's contribution -- mode scrambling and drift on top of the interference
term -- and not an artifact of which random waveform happened to land at a
given shot index.

Reads a bounded sample of shots (never a whole channel: one channel is
0.66 GB).
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

import h5py
from _figcommon import COLORS, FIGSIZE_HALF, FREE_SPACE_H5, MMFIBER_H5, parse_args, save

CHANNEL = 'RP1_CH2'  # 635 nm photodiode
N_SHOTS = 1024  # shots averaged for the spectrum; ~134 MB read per file


def mean_spectrum(
    h5_path: Path, channel: str, n_shots: int
) -> tuple[np.ndarray, np.ndarray]:
    """Amplitude spectrum of ``channel`` averaged over the first ``n_shots``."""
    with h5py.File(h5_path, 'r') as f:
        block = np.asarray(f[channel][:n_shots, :], dtype=np.float64)
        sample_rate = float(f.attrs['sample_rate'])
    block = block - block.mean(axis=1, keepdims=True)
    spectrum = np.abs(np.fft.rfft(block, axis=1)).mean(axis=0)
    freq = np.fft.rfftfreq(block.shape[1], d=1.0 / sample_rate)
    return freq, spectrum


def main() -> None:
    args = parse_args(__doc__ or '')

    fig, ax = plt.subplots(figsize=FIGSIZE_HALF, constrained_layout=True)

    sources = (
        ('free space', FREE_SPACE_H5, COLORS['accent']),
        ('mm fiber', MMFIBER_H5, COLORS['ch635']),
    )

    for label, path, color in sources:
        freq, spectrum = mean_spectrum(path, CHANNEL, N_SHOTS)
        keep = (freq > 0) & (freq <= 20e3)
        ax.loglog(freq[keep], spectrum[keep], color=color, label=label, alpha=0.85)
    ax.set_xlabel('frequency (Hz)')
    ax.set_ylabel('mean |FFT| (arb.)')
    ax.set_title(f'635 nm mean amplitude spectrum, N = {N_SHOTS} shots')
    ax.legend(loc='lower left')

    save(fig, args.output)


if __name__ == '__main__':
    main()
